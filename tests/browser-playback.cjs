const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({...(process.env.CHROMIUM_PATH ? {executablePath:process.env.CHROMIUM_PATH} : {})});
 const page=await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
 const base=process.env.SITE_URL || 'http://127.0.0.1:8765';
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(`${base}/watch.html#e1`);
 await page.getByRole('button',{name:'Auto speed on',exact:true}).first().waitFor();
 const ep=page.locator('[data-ep="e1"]');
 const v=ep.locator('video');
 await v.evaluate(v=>{v.load()});
 await page.waitForFunction(()=>document.querySelector('[data-ep="e1"] video').readyState>=1);
 assert.equal(await v.evaluate(v=>v.playbackRate),16);
 await v.evaluate(v=>{v.currentTime=48});
 await page.waitForFunction(()=>document.querySelector('[data-ep="e1"] video').playbackRate===4);
 await v.evaluate(v=>{v.currentTime=55});
 await page.waitForFunction(()=>document.querySelector('[data-ep="e1"] video').playbackRate===16);
 await ep.getByRole('button',{name:'Auto speed on',exact:true}).click();
 assert.equal(await v.evaluate(v=>v.playbackRate),1);
 await v.evaluate(v=>{v.currentTime=48;v.playbackRate=8});
 assert.equal(await ep.getByRole('button',{name:'Auto speed off',exact:true}).getAttribute('aria-pressed'),'false');
 await ep.getByRole('button',{name:'Auto speed off',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('[data-ep="e1"] video').playbackRate===4);
 await v.evaluate(v=>{v.playbackRate=2});
 await ep.getByRole('button',{name:'Auto speed off',exact:true}).waitFor();
 await ep.scrollIntoViewIfNeeded();
 await page.goto(`${base}/`);
 assert.equal(await page.locator('.agp-author').count(),5);
 assert(!(await page.locator('body').innerText()).includes('Xiaobai'));
 
 await page.setViewportSize({width:390,height:844});
 await page.goto(`${base}/watch.html#e2`);
 const ep2=page.locator('[data-ep="e2"]');
 await ep2.getByRole('button',{name:'Auto speed on',exact:true}).waitFor();
 const v2=ep2.locator('video');await v2.evaluate(v=>v.load());
 await page.waitForFunction(()=>document.querySelector('[data-ep="e2"] video').readyState>=1);
 const data=await(await page.request.get(`${base}/data/viewer/e2.json`)).json();
 const [start,end]=data.lanes.motion[0];
 await v2.evaluate((v,t)=>{v.currentTime=t},(start+end)/4);
 await page.waitForFunction(()=>document.querySelector('[data-ep="e2"] video').playbackRate===2);
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await ep2.scrollIntoViewIfNeeded();
 assert.deepEqual(errors,[]);await browser.close();
 console.log('PASS automatic rates, motion boundaries, seek, manual override, re-enable, double-speed encoding, five authors, mobile width, and no page errors');
})().catch(e=>{console.error(e);process.exit(1)});
